#!/usr/bin/env node
/**
 * 从已提交的 OpenAPI spec 生成前端接口类型。
 *
 * 设计约束（见 openspec/changes/admin-frontend-closure/design.md D4）：
 *   - 只读 `apps/swagger-docs/swagger-spec.json`，不联网、不启动后端；
 *   - 输出 `src/type/generated-api.d.ts`，文件头标注 generated；
 *   - 生成结果必须可重复：同样的 spec 产出逐字节相同的文件（CI 靠 diff 判定）。
 *
 * 刷新 spec 是另一件事：`yarn workspace @lucky/api export:swagger:full`
 * （会启动 AppModule，属于人工/发布前步骤）。
 */
import { execFileSync } from 'node:child_process';
import {
  mkdirSync,
  readFileSync,
  writeFileSync,
} from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const adminRoot = resolve(here, '..');
const specPath = resolve(adminRoot, '../swagger-docs/swagger-spec.json');
const outPath = resolve(adminRoot, 'src/type/generated-api.d.ts');

const require = createRequire(import.meta.url);
// 包 exports 把子路径映射成了 .mjs，不能直接 resolve bin/cli.js；
// 从包入口反推包根目录，再用真实文件名定位 CLI。
const pkgEntry = require.resolve('openapi-typescript');
const cliPath = resolve(dirname(pkgEntry), '..', 'bin/cli.js');

console.log(
  `[api-types] ${relative(process.cwd(), specPath)} -> ${relative(process.cwd(), outPath)}`,
);

mkdirSync(dirname(outPath), { recursive: true });
execFileSync(process.execPath, [cliPath, specPath, '-o', outPath], {
  stdio: 'inherit',
});

const banner = `/**
 * AUTO-GENERATED by scripts/generate-api-types.mjs — do not edit.
 * Source: apps/swagger-docs/swagger-spec.json
 * Regenerate: yarn workspace @lucky/admin-next generate:api-types
 */
/* eslint-disable */

`;

writeFileSync(outPath, banner + readFileSync(outPath, 'utf8'));
console.log('[api-types] done');
