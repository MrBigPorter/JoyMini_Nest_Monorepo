/**
 * 策略型兜底：当 AI 运行时失败（LLM/工具异常）时，对少数“有明确政策答案”
 * 的问题给固定回复，避免无差别转人工。余额/券状态仍建议用户稍后重试或去 App 查。
 */
export function policyFallback(message: string): string | null {
  const text = message.toLowerCase();

  if (/(审核|认证).{0,8}(多久|多长时间)|(多久|多长时间).{0,8}(审核|认证)/.test(message)) {
    return '实名认证审核通常需要 1–3 个工作日。如果当前是“草稿/未提交”，请先在 App「我的 → 实名认证」提交资料。';
  }

  if (
    /(配送|送到|发货|物流).{0,12}(几天|多久|范围|时间|宿务|cebu)|(几天|多久).{0,12}(送到|配送|发货)/i.test(
      message,
    )
  ) {
    return '标准配送时效：Metro Manila 约 2–4 个工作日，省级地区约 5–8 个工作日，偏远地区可能更长；具体以下单结算页显示为准。';
  }

  if (/(券|优惠券).{0,10}(过期|有效期)|(过期|有效期).{0,10}(券|优惠券)/.test(message)) {
    return '如果当前没有优惠券，就没有过期时间。你可以在 App「我的 → 优惠券」查看每张券的有效期和状态。';
  }

  if (/(余额|钱包).{0,10}(多少|查询|还有)|balance/i.test(text)) {
    return '余额查询暂时失败，请稍后再试，或在 App「我的 → 钱包」查看当前余额。';
  }

  return null;
}
